# Publish validated NRB workbook vintages into a GitHub data-cache worktree.
#
# Usage from GitHub Actions:
#   Rscript data-raw/update-mirror.R <output-directory>
#
# Bootstrap from an already audited cache (used only to seed the branch):
#   Rscript data-raw/update-mirror.R <output-directory> <cache-directory>

args <- commandArgs(trailingOnly = TRUE)
if (!length(args) %in% c(1L, 2L)) {
  stop("Expected an output directory and, optionally, an audited cache directory.")
}

output_dir <- path.expand(args[[1L]])
dir.create(output_dir, recursive = TRUE, showWarnings = FALSE)
output_dir <- normalizePath(output_dir, winslash = "/", mustWork = TRUE)

pkgload::load_all(".", export_all = FALSE, helpers = FALSE, quiet = TRUE)
ids <- lc_catalog()$dataset_id

if (length(args) == 2L) {
  cache_dir <- normalizePath(path.expand(args[[2L]]), winslash = "/", mustWork = TRUE)
  options(lcNRB.cache_dir = cache_dir)
  expected <- utils::read.csv(
    file.path("data-raw", "source-manifest.csv"), stringsAsFactors = FALSE
  )
  observed <- lc_cache_info()
  for (id in ids) {
    row <- lcNRB:::lc_latest_manifest(id)
    if (is.null(row)) stop("Audited cache is missing `", id, "`.")
    expected_hash <- expected$sha256[match(id, expected$dataset_id)]
    if (is.na(expected_hash) || !identical(row$sha256[[1L]], expected_hash)) {
      stop("Audited cache hash does not match data-raw/source-manifest.csv for `", id, "`.")
    }
    path <- row$raw_path[[1L]]
    attr(path, "source_url") <- row$source_url[[1L]]
    lcNRB:::lc_process_dataset(id, path)
  }
  updates <- tibble::tibble(
    dataset_id = ids, source = "audited-cache", status = "seeded"
  )
} else {
  cache_dir <- tempfile("lcnrb-mirror-cache-")
  dir.create(cache_dir, recursive = TRUE, showWarnings = FALSE)
  on.exit(unlink(cache_dir, recursive = TRUE, force = TRUE), add = TRUE)
  options(lcNRB.cache_dir = normalizePath(cache_dir, winslash = "/"))
  updates <- lc_update(ids, dry_run = FALSE, source = "nrb")
}

manifest_path <- file.path(output_dir, "manifest.csv")
if (file.exists(manifest_path)) {
  mirror <- lcNRB:::lc_validate_mirror_manifest(utils::read.csv(
    manifest_path, stringsAsFactors = FALSE, check.names = FALSE
  ))
} else {
  mirror <- tibble::tibble(
    dataset_id = character(), source_url = character(), retrieved_at = character(),
    sha256 = character(), parser_version = character(), file_type = character(),
    mirror_path = character(), validated_at = character(), current = logical(),
    rows = integer(), indicators = integer()
  )
}

validated_at <- lcNRB:::lc_now_utc()
registry <- lcNRB:::lc_dataset_registry()
for (id in ids) {
  cached <- lcNRB:::lc_latest_manifest(id, require_processed = TRUE)
  if (is.null(cached)) stop("No validated processed cache entry for `", id, "`.")
  data <- readRDS(cached$processed_path[[1L]])
  lc_validate(data)
  if (!identical(unique(data$source_hash), cached$sha256[[1L]])) {
    stop("Processed provenance hash mismatch for `", id, "`.")
  }

  type <- registry$file_type[match(id, registry$dataset_id)]
  relative_path <- paste0("data/", id, "/", cached$sha256[[1L]], ".", type)
  target <- do.call(
    file.path,
    as.list(c(output_dir, strsplit(relative_path, "/", fixed = TRUE)[[1L]]))
  )
  dir.create(dirname(target), recursive = TRUE, showWarnings = FALSE)
  if (!file.exists(target) && !file.copy(cached$raw_path[[1L]], target)) {
    stop("Failed to copy mirror asset for `", id, "`.")
  }
  target_hash <- digest::digest(file = target, algo = "sha256")
  if (!identical(target_hash, cached$sha256[[1L]])) {
    stop("Copied mirror asset hash mismatch for `", id, "`.")
  }

  mirror$current[mirror$dataset_id == id] <- FALSE
  same <- mirror$dataset_id == id & mirror$sha256 == cached$sha256[[1L]]
  retrieved_at <- if (any(same)) {
    mirror$retrieved_at[which(same)[[1L]]]
  } else {
    cached$retrieved_at[[1L]]
  }
  record <- tibble::tibble(
    dataset_id = id,
    source_url = cached$source_url[[1L]],
    retrieved_at = retrieved_at,
    sha256 = cached$sha256[[1L]],
    parser_version = cached$parser_version[[1L]],
    file_type = type,
    mirror_path = relative_path,
    validated_at = validated_at,
    current = TRUE,
    rows = nrow(data),
    indicators = length(unique(data$indicator_id))
  )
  if (any(same)) {
    mirror[which(same)[[1L]], ] <- record
  } else {
    mirror <- dplyr::bind_rows(mirror, record)
  }
}

mirror <- mirror[order(mirror$dataset_id, mirror$retrieved_at), , drop = FALSE]
mirror <- lcNRB:::lc_validate_mirror_manifest(mirror)
utils::write.csv(mirror, manifest_path, row.names = FALSE, na = "")

writeLines(c(
  "# lcNRB validated data mirror",
  "",
  "This branch is generated by the scheduled lcNRB mirror workflow.",
  "It stores the original NRB workbook bytes by SHA-256 content hash.",
  "`manifest.csv` retains the official NRB URL, retrieval time, parser version,",
  "validation time, row count, and indicator count for every published vintage.",
  "A failed download or parser validation leaves the previous mirror unchanged.",
  "",
  "This mirror is independent and is not affiliated with or endorsed by NRB."
), file.path(output_dir, "README.md"), useBytes = TRUE)

print(updates)
print(mirror[mirror$current, , drop = FALSE])
cat("Validated mirror update: PASS\n")
